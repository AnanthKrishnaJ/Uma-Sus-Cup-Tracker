with open('suscup1.html', 'r', encoding='utf-8') as f:
    content = f.read()

# 1. Inject JSON Data
start = content.find('const INITIAL_DATA = ')
end = content.find('const UMA_DATABASE =')
json_str = content[start + 21:end].strip().rstrip(';')
data = json.loads(json_str)

if not any(r.get('id') == 14 for r in data['races']):
    data['races'].insert(0, suscup14)

new_json = json.dumps(data, indent=4)
content = content[:start + 21] + new_json + ';\n\n        ' + content[end:]

# 2. Add special-week to UMA_DATABASE
if '"special-week":' not in content and 'special-week:' not in content:
    db_marker = 'const UMA_DATABASE = {'
    insert_str = '\n    "special-week": { id: "special-week", name: "Special Week", type: "Uma Musume", version: "Original / Default", url: "https://gametora.com/umamusume/characters/special-week", image: "https://gametora.com/images/umamusume/characters/chara_stand_1001_100101.png" },'
    content = content.replace(db_marker, db_marker + insert_str)

# 3. Patch date sort so "Soon" is treated as future date
sort_target = "races.sort((a, b) => new Date(a.date) - new Date(b.date));"
sort_replace = """races.sort((a, b) => {
                    let da = new Date(a.date);
                    let db = new Date(b.date);
                    if (isNaN(da)) da = new Date('2099-01-01');
                    if (isNaN(db)) db = new Date('2099-01-01');
                    return da - db;
                });"""
if sort_target in content:
    content = content.replace(sort_target, sort_replace)

with open('suscup1.html', 'w', encoding='utf-8') as f:
    f.write(content)

print("SUS CUP 14 data applied!")
